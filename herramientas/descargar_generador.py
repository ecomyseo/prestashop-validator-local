# -*- coding: utf-8 -*-
"""
Descarga módulos de referencia del generador OFICIAL (validator.prestashop.com/generator).

Un módulo salido del generador oficial es el "contrato" de lo que el validator acepta:
sirve de goal positivo (el validator local no puede darle errores que el oficial no da).

Uso:
    python herramientas/descargar_generador.py [carpeta_destino]
"""
import os
import re
import sys
import zipfile
import io

import requests

BASE = 'https://validator.prestashop.com'

CASOS = [
    # nombre, tipo, tab, min, max, hooks, bd, confirm_uninstall
    ('refstandard', 'standard', 'front_office_features', '1.7', '9.0',
     ['header', 'displayBackOfficeHeader', 'displayHome', 'actionValidateOrder'], '1', '1'),
    ('refpayment', 'payment', 'payments_gateways', '1.7', '9.0',
     ['paymentOptions', 'paymentReturn'], '1', '0'),
    ('refshipping', 'shipping', 'shipping_logistics', '1.7', '9.0',
     ['updateCarrier'], '1', '0'),
    ('refservice', 'service', 'administration', '8.0', '9.0', [], '0', '0'),
]


def main():
    destino = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'oficial', 'generador')
    os.makedirs(destino, exist_ok=True)
    s = requests.Session()
    s.headers['User-Agent'] = 'Mozilla/5.0 (validator-local)'
    for nombre, tipo, tab, vmin, vmax, hooks, bd, confirm in CASOS:
        html = s.get(BASE + '/generator', timeout=60).text
        token = re.search(r'name="_token" value="([^"]+)"', html).group(1)
        datos = [
            ('_token', token), ('module_type', tipo), ('tab', tab), ('name', nombre),
            ('display_name', 'Reference ' + tipo + ' module'),
            ('description', 'Reference module generated by the official PrestaShop generator.'),
            ('author', 'Ecom Experts'), ('version_maj', '1'), ('version_med', '0'), ('version_min', '0'),
            ('confirm_uninstall', confirm), ('uninstall_message', 'Are you sure you want to uninstall?'),
            ('database', bd), ('need_instance', '0'),
            ('version_compliancy[min]', vmin), ('version_compliancy[max]', vmax),
        ]
        for h in hooks:
            datos.append(('hooks_select[]', h))
        r = s.post(BASE + '/generator', data=datos, timeout=120)
        tipo_resp = r.headers.get('content-type', '')
        if 'zip' not in tipo_resp and not r.content.startswith(b'PK'):
            print('FALLO', nombre, r.status_code, tipo_resp, r.text[:300].replace('\n', ' '))
            continue
        ruta = os.path.join(destino, nombre + '.zip')
        with open(ruta, 'wb') as f:
            f.write(r.content)
        with zipfile.ZipFile(io.BytesIO(r.content)) as z:
            n = len(z.namelist())
            z.extractall(destino)
        print('OK', nombre, len(r.content), 'bytes,', n, 'entradas')


if __name__ == '__main__':
    main()
